const escapeHtml = (text: string) =>
  text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const sentence = (text: string) => {
  const trimmed = text.trim();
  const capital = trimmed.charAt(0).toUpperCase() + trimmed.slice(1);
  return /[.!?]$/.test(capital) ? capital : `${capital}.`;
};
const lowerFirst = (text: string) =>
  /^[A-Z][a-z]/.test(text) ? text.charAt(0).toLowerCase() + text.slice(1) : text;
/** Catalogue text speaks of "the owner"; the website speaks to the reader. */
const yours = (text: string) => text.replace(/\bthe owner's\b/g, "your");
const joinList = (items: string[]) =>
  items.length <= 1
    ? (items[0] ?? "")
    : `${items.slice(0, -1).join("; ")} and ${items[items.length - 1]}`;

/** "AI Bookkeeper", but never "AI AI ...". */
export const aiName = (agent: AgentTemplate) =>
  /^AI\b/.test(agent.name) ? agent.name : `AI ${agent.name}`;

/** The first candidate that fits the site's 30–70 character title rule (counted as served, escaped). */
function fitTitle(candidates: string[]) {
  return (
    candidates.find((title) => escapeHtml(title).length >= 30 && escapeHtml(title).length <= 70) ??
    candidates[candidates.length - 1]
  );
}

export function agentTitle(agent: AgentTemplate) {
  const name = aiName(agent);
  return fitTitle([
    `${name}: Free AI Coworker for Windows | Sahkarmi`,
    `${name}: Free AI Coworker | Sahkarmi`,
    `${name} | Free AI Coworker`,
    `${agent.name} | Sahkarmi`,
  ]);
}

export function agentDescription(agent: AgentTemplate) {
  const summary = sentence(agent.summary);
  const tails = [
    " Free, open-source AI coworker for Windows.",
    " Free AI coworker for Windows.",
    " Free on Windows.",
    "",
  ];
  return (
    tails.map((tail) => summary + tail).find((text) => escapeHtml(text).length <= 170) ?? summary
  );
}

