/** Every generated page, keyed by its path under website/. */
export function renderCoworkerPages(): Map<string, string> {
  const pages = new Map<string, string>();
  pages.set("coworkers/index.html", renderHubPage());
  for (const category of AGENT_CATEGORIES)
    pages.set(`coworkers/${category}.html`, renderCategoryPage(category));
  for (const agent of AGENT_CATALOG)
    pages.set(`coworkers/${agent.id}.html`, renderAgentPage(agent));
  return pages;
}

