// Builds the website's video library (/videos/) from website/videos/library.json: one library
// page and one watch page per film, each indexable with VideoObject structured data.
// scripts/build-video-library.ts writes them; scripts/add-video.ts adds a film and rebuilds;
// video-library-lib.test.ts fails when the pages are stale.
import { readFileSync } from "node:fs";
import { join } from "node:path";

export const ORIGIN = "https://sahkarmi.site";
const REPO = "https://github.com/ganguydhrubo/sahakarmi";
// Rewritten to the newest installer on every deploy (scripts/inject-downloads.mjs).
const INSTALLER = `${REPO}/releases/download/v0.33.0/Sahkarmi-0.33.0-x64.exe`;
const STORE = "https://apps.microsoft.com/detail/9PD6BP3NGVST";
const SITEMAP_START = "  <!-- videos:start (generated by scripts/build-video-library.ts) -->";
const SITEMAP_END = "  <!-- videos:end -->";
export const HUB_PATH = "/videos/";

export interface Video {
  id: string;
  title: string;
  summary: string;
  category: string;
  seconds: number;
  /** YYYY-MM-DD, the day it was published. */
  date: string;
  width: number;
  height: number;
  /** Second of the film the poster picture was taken from (scripts/add-video.ts). */
  posterAt?: number;
  transcript: string[];
}

export const LIBRARY_FILE = join(__dirname, "..", "website", "videos", "library.json");

export function loadLibrary(file = LIBRARY_FILE): Video[] {
  return (JSON.parse(readFileSync(file, "utf8")) as { videos: Video[] }).videos;
}

export const watchPath = (video: Video) => `/videos/${video.id}.html`;
export const fileUrl = (video: Video) => `/assets/videos/${video.id}.mp4`;
export const posterUrl = (video: Video) => `/assets/videos/${video.id}.jpg`;

const escapeHtml = (text: string) =>
  text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/** 81.9 -> "1:21" (rounded down, as video players show it) */
export const clock = (seconds: number) => {
  const total = Math.floor(seconds);
  return `${Math.floor(total / 60)}:${String(total % 60).padStart(2, "0")}`;
};
/** 81.4 -> "PT1M21S" (schema.org duration) */
export const isoDuration = (seconds: number) => {
  const total = Math.round(seconds);
  return `PT${Math.floor(total / 60)}M${total % 60}S`;
};

/** A title of 30-70 characters (as the site check wants), from the film's own title. */
export function pageTitle(video: Video) {
  const candidates = [
    `${video.title} | Sahkarmi video`,
    `${video.title} | Sahkarmi`,
    video.title,
    `${video.title.slice(0, 58).trimEnd()}… | Sahkarmi`,
  ];
  return (
    candidates.find((title) => escapeHtml(title).length >= 30 && escapeHtml(title).length <= 70) ??
    candidates[candidates.length - 1]
  );
}

export function pageDescription(video: Video) {
  const base = `${clock(video.seconds)} film. ${video.summary}`;
  if (base.length <= 170) return base;
  return `${base.slice(0, 168).replace(/\s+\S*$/, "")}…`;
}

function videoObject(video: Video) {
  return {
    "@type": "VideoObject",
    "@id": `${ORIGIN}${watchPath(video)}#video`,
    name: video.title,
    description: video.summary,
    thumbnailUrl: [`${ORIGIN}${posterUrl(video)}`],
    uploadDate: `${video.date}T09:00:00+05:30`,
    duration: isoDuration(video.seconds),
    contentUrl: `${ORIGIN}${fileUrl(video)}`,
    embedUrl: `${ORIGIN}${watchPath(video)}`,
    width: video.width,
    height: video.height,
    inLanguage: "en",
    isFamilyFriendly: true,
    transcript: video.transcript.join(" "),
    publisher: { "@id": `${ORIGIN}/#organization` },
    about: { "@id": `${ORIGIN}/#software` },
  };
}

