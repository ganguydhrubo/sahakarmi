interface PageInput {
  path: string;
  title: string;
  description: string;
  image: string;
  ogType: string;
  crumbs: { name: string; path: string }[];
  graph: object[];
  body: string;
  data: Video[];
}

/** What the player script needs, embedded in the page (no extra request). */
function playerData(videos: Video[]) {
  return JSON.stringify(
    videos.map((video) => ({
      id: video.id,
      title: video.title,
      category: video.category,
      src: fileUrl(video),
      poster: posterUrl(video),
      page: watchPath(video),
      length: clock(video.seconds),
    })),
  ).replace(/</g, "\\u003c");
}

