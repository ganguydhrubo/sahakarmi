function card(video: Video, index: number) {
  return `      <li class="vcard" data-category="${escapeHtml(video.category)}"><a href="${watchPath(video)}" data-video="${video.id}"><span class="vthumb"><img src="${posterUrl(video)}" width="540" height="960" alt="" ${index < 4 ? 'fetchpriority="high"' : 'loading="lazy"'} decoding="async" /><span class="vplay" aria-hidden="true"></span><span class="vlen">${clock(video.seconds)}</span></span><span class="vmeta"><span class="vcat">${escapeHtml(video.category)}</span><span class="vtitle">${escapeHtml(video.title)}</span></span></a></li>`;
}

function grid(videos: Video[]) {
  return `    <ul class="vgrid" id="vgrid">
${videos.map(card).join("\n")}
    </ul>`;
}

export function renderHubPage(videos: Video[]) {
  const minutes = Math.round(videos.reduce((sum, video) => sum + video.seconds, 0) / 60);
  const categories = [...new Set(videos.map((video) => video.category))];
  const title = "Sahkarmi videos: see free AI coworkers at work";
  const description = `${videos.length} short films (${minutes} minutes) showing Sahkarmi's free AI coworkers doing real work on a Windows PC: accounts, HR, sales, shops, jobs and more.`;
  const chips = [
    `<button type="button" class="vchip" aria-pressed="true" data-filter="">All <b>${videos.length}</b></button>`,
    ...categories.map(
      (category) =>
        `<button type="button" class="vchip" aria-pressed="false" data-filter="${escapeHtml(category)}">${escapeHtml(category)} <b>${videos.filter((video) => video.category === category).length}</b></button>`,
    ),
  ].join("");
  const body = `    <section class="vhero">
      <p class="eyebrow">Video library</p>
      <h1>Watch Sahkarmi at work</h1>
      <p class="lead">Short films of free AI coworkers doing real jobs on a Windows PC. Tap any film to watch it full screen, then swipe up for the next one.</p>
      <p class="vstats"><span><b>${videos.length}</b> films</span><span><b>${minutes}</b> minutes</span><span>New films added often</span></p>
    </section>
    <div class="vchips" role="toolbar" aria-label="Show films about">${chips}</div>
${grid(videos)}
    <p class="vempty" id="vempty" hidden>No films in this group yet.</p>`;
  return page({
    path: HUB_PATH,
    title,
    description,
    image: posterUrl(videos[0] as Video),
    ogType: "website",
    crumbs: [
      { name: "Sahkarmi", path: "/" },
      { name: "Videos", path: HUB_PATH },
    ],
    graph: [
      {
        "@type": "CollectionPage",
        "@id": `${ORIGIN}${HUB_PATH}#page`,
        url: `${ORIGIN}${HUB_PATH}`,
        name: title,
        description,
        isPartOf: { "@id": `${ORIGIN}/#website` },
        inLanguage: "en",
        mainEntity: {
          "@type": "ItemList",
          numberOfItems: videos.length,
          itemListElement: videos.map((video, index) => ({
            "@type": "ListItem",
            position: index + 1,
            url: `${ORIGIN}${watchPath(video)}`,
            name: video.title,
          })),
        },
      },
    ],
    body,
    data: videos,
  });
}

export function renderWatchPage(video: Video, videos: Video[]) {
  const others = videos.filter((other) => other.id !== video.id);
  // Same group first, then the rest, so "next" feels related.
  const more = [
    ...others.filter((other) => other.category === video.category),
    ...others.filter((other) => other.category !== video.category),
  ].slice(0, 8);
  const body = `    <article class="vwatch">
      <div class="vwatch-player">
        <div class="vframe">
          <video id="vmain" controls playsinline preload="metadata" poster="${posterUrl(video)}" width="${video.width}" height="${video.height}" src="${fileUrl(video)}"></video>
        </div>
        <button type="button" class="btn vfull" data-video="${video.id}">Watch full screen</button>
      </div>
      <div class="vwatch-copy">
        <p class="eyebrow">${escapeHtml(video.category)} · ${clock(video.seconds)}</p>
        <h1>${escapeHtml(video.title)}</h1>
        <p class="lead">${escapeHtml(video.summary)}</p>
        <p class="vdate">Published <time datetime="${video.date}">${new Date(`${video.date}T00:00:00Z`).toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric", timeZone: "UTC" })}</time> · English</p>
        <details class="vtranscript" open>
          <summary>What is said in this film</summary>
${video.transcript.map((line) => `          <p>${escapeHtml(line)}</p>`).join("\n")}
        </details>
      </div>
    </article>
    <h2>More films</h2>
${grid(more)}
    <p><a href="${HUB_PATH}">See all ${videos.length} films</a></p>`;
  return page({
    path: watchPath(video),
    title: pageTitle(video),
    description: pageDescription(video),
    image: posterUrl(video),
    ogType: "video.other",
    crumbs: [
      { name: "Sahkarmi", path: "/" },
      { name: "Videos", path: HUB_PATH },
      { name: video.title, path: watchPath(video) },
    ],
    graph: [
      {
        "@type": "WebPage",
        "@id": `${ORIGIN}${watchPath(video)}#page`,
        url: `${ORIGIN}${watchPath(video)}`,
        name: pageTitle(video),
        description: pageDescription(video),
        isPartOf: { "@id": `${ORIGIN}/#website` },
        primaryImageOfPage: `${ORIGIN}${posterUrl(video)}`,
        mainEntity: { "@id": `${ORIGIN}${watchPath(video)}#video` },
        inLanguage: "en",
      },
      videoObject(video),
    ],
    body,
    // The full-screen feed starts here and continues through the rest of the library.
    data: [video, ...more, ...others.filter((other) => !more.includes(other))],
  });
}

export function renderVideoPages(videos = loadLibrary()): Map<string, string> {
  const pages = new Map<string, string>();
  pages.set("videos/index.html", renderHubPage(videos));
  for (const video of videos) pages.set(`videos/${video.id}.html`, renderWatchPage(video, videos));
  return pages;
}

export function videoUrls(videos = loadLibrary()) {
  return [`${ORIGIN}${HUB_PATH}`, ...videos.map((video) => `${ORIGIN}${watchPath(video)}`)];
}

/** The sitemap with its generated video block replaced (or added before </urlset>). */
export function withVideoSitemap(sitemap: string, videos = loadLibrary()) {
  const block = [
    SITEMAP_START,
    ...videoUrls(videos).map((loc) => `  <url>\n    <loc>${loc}</loc>\n  </url>`),
    SITEMAP_END,
  ].join("\n");
  const start = sitemap.indexOf(SITEMAP_START);
  const end = sitemap.indexOf(SITEMAP_END);
  if (start !== -1 && end !== -1)
    return sitemap.slice(0, start) + block + sitemap.slice(end + SITEMAP_END.length);
  return sitemap.replace("</urlset>", `${block}\n</urlset>`);
}

/** A short id for a new film from its title: "Clinic front desk" -> "clinic-front-desk". */
export function slugFor(title: string, taken: Set<string>) {
  const base =
    title
      .toLowerCase()
      .normalize("NFKD")
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "")
      .slice(0, 48)
      .replace(/-+$/g, "") || "film";
  let id = base;
  for (let n = 2; taken.has(id); n += 1) id = `${base}-${n}`;
  return id;
}

const TEASER_START =
  "        <!-- videos-teaser:start (generated by scripts/build-video-library.ts) -->";
const TEASER_END = "        <!-- videos-teaser:end -->";

/** The home page with its row of the newest films (and the film count) rebuilt. */
export function withHomeTeaser(html: string, videos = loadLibrary()) {
  const start = html.indexOf(TEASER_START);
  const end = html.indexOf(TEASER_END);
  if (start === -1 || end === -1) throw new Error("index.html has no videos-teaser block");
  const items = videos
    .slice(0, 5)
    .map(
      (video) =>
        `          <li><a href="${watchPath(video)}"><img src="${posterUrl(video)}" width="540" height="960" alt="Film: ${escapeHtml(video.title)}" loading="lazy" decoding="async" /><span class="vt-len">${clock(video.seconds)}</span><span class="vt-title" aria-hidden="true">${escapeHtml(video.title)}</span></a></li>`,
    )
    .join("\n");
  const block = `${TEASER_START}
        <ul class="vteaser-row reveal" aria-label="${videos.length} films">
${items}
          <li class="vt-more"><a href="${HUB_PATH}"><b>${videos.length}</b><span>films in the library</span></a></li>
        </ul>
`;
  return html.slice(0, start) + block + html.slice(end);
}
